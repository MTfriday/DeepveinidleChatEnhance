#!/usr/bin/env node
// 发布前自检：把油猴脚本开发规范里最容易漏的几条做成可执行检查。
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const file = path.join(root, 'dvi-chat-plus.user.js');
const code = readFileSync(file, 'utf8');

const results = [];
const add = (ok, label, detail) => results.push({ ok, label, detail });

// 1. 语法
try {
    execFileSync(process.execPath, ['--check', file], { stdio: 'pipe' });
    add(true, '语法可解析');
} catch (err) {
    add(false, '语法可解析', String(err.stderr || err.message).trim().split('\n')[0]);
}

// 2. 元数据块
const head = code.match(/\/\/ ==UserScript==([\s\S]*?)\/\/ ==\/UserScript==/);
if (!head) {
    add(false, '元数据块存在');
} else {
    add(true, '元数据块存在');
    const meta = {};
    for (const line of head[1].split('\n')) {
        const m = line.match(/^\s*\/\/\s*@([A-Za-z]+)\s+(.+)$/);
        if (m) (meta[m[1]] ||= []).push(m[2].trim());
    }

    const required = ['name', 'description', 'namespace', 'version', 'license', 'match'];
    const missing = required.filter((k) => !meta[k]);
    add(missing.length === 0, '六个必填字段齐全', missing.length ? '缺 ' + missing.join(' / ') : '');

    const version = (meta.version || [])[0];
    const constVersion = (code.match(/SCRIPT_VERSION\s*=\s*'([^']+)'/) || [])[1];
    add(version === constVersion, '版本号两处一致', `@version=${version} SCRIPT_VERSION=${constVersion}`);

    const grants = meta.grant || [];
    const usesGM = /\bGM_[A-Za-z]+|\bGM\.[A-Za-z]+/.test(code);
    if (!grants.length) {
        add(false, '@grant 已声明', '缺少 @grant');
    } else if (grants.includes('none') && usesGM) {
        add(false, '@grant 与实际使用一致', '@grant none 但正文调用了 GM API');
    } else if (!grants.includes('none') && !usesGM) {
        add(false, '@grant 与实际使用一致', '声明了特权但正文未使用任何 GM API');
    } else {
        add(true, '@grant 与实际使用一致', grants.join(','));
    }

    if (/GM_xmlhttpRequest/.test(code) && !meta.connect) {
        add(false, '@connect 覆盖跨域请求', '用了 GM_xmlhttpRequest 但没有 @connect');
    } else if (!/GM_xmlhttpRequest/.test(code)) {
        add(true, '@connect 无需声明', '未使用 GM_xmlhttpRequest');
    } else {
        add(true, '@connect 覆盖跨域请求');
    }
}

// 3. 结构：IIFE + 严格模式
add(/\(function\s*\(\s*\)\s*\{/.test(code), 'IIFE 包裹');
add(/['"]use strict['"]/.test(code), "含 'use strict'");

// 4. 注释规范：不许长横线装饰
const dashLines = [];
code.split('\n').forEach((line, i) => {
    if (/^\s*(?:\/\/|\/\*|\*)\s*[-=]{6,}/.test(line)) dashLines.push(i + 1);
    else if (/[-=]{6,}\s*\*\/\s*$/.test(line) && /\/\*/.test(line) && !/^\s*\/\/ @/.test(line)) dashLines.push(i + 1);
});
add(dashLines.length === 0, '无长横线装饰注释', dashLines.length ? '行 ' + dashLines.join(', ') : '');

// 5. 不许 AI 生成标记
const aiMarks = ['generated by', 'ai-generated', 'ai generated', '由 ai 生成', 'chatgpt', 'copilot'];
const hit = aiMarks.filter((k) => code.toLowerCase().includes(k));
add(hit.length === 0, '无 AI 生成标记', hit.join(', '));

// 输出
const name = path.basename(file);
console.log(`自检 ${name}`);
console.log('─'.repeat(46));
for (const r of results) {
    const mark = r.ok ? 'OK  ' : 'FAIL';
    console.log(`${mark} ${r.label}${r.detail && !r.ok ? ' — ' + r.detail : ''}`);
}
const failed = results.filter((r) => !r.ok).length;
console.log('─'.repeat(46));
console.log(failed ? `${failed} 项未通过` : '全部通过，可以发布');
process.exit(failed ? 1 : 0);
